#!/usr/bin/env python3
"""Generate the protocol evidence reference; --check fails if it is stale."""

import argparse
import json
from pathlib import Path
import re


ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "docs/data/protocol-mappings.json"
OUTPUT = ROOT / "docs/protocol-mappings.md"
FIELDS = {"id", "source_field", "source_meaning", "target_meaning",
          "source_evidence", "target_evidence", "status"}


def render():
    data = json.loads(SOURCE.read_text(encoding="utf-8"))
    if set(data) != {"version", "mappings"} or data["version"] != 1 or not data["mappings"]:
        raise ValueError("Expected a version 1 protocol mapping table")
    lines = [
        "# 协议映射证据", "",
        "<!-- Generated by scripts/generate-protocol-mappings.py; edit docs/data/protocol-mappings.json. -->", "",
        "本页由[仓库数据表](data/protocol-mappings.json)生成，记录来源与目标的解释、固定源码证据及实现状态。",
        "`Mapped` 表示已实现；源码研究与字段声明一致性测试不等于真实服务端、设备或网络的运行时等价证明。",
        "数据表不参与运行时转换；节点 IR 只保留解释后的值及是否显式提供的标记，不携带字段路径或文档规则 ID。", "",
        "更新数据表后运行 `python3 scripts/generate-protocol-mappings.py`；",
        "使用 `python3 scripts/generate-protocol-mappings.py --check` 检查生成文档是否过时。",
        "测试从同一数据表生成用例，核对固定 revision、唯一标识及当前协议 Schema；业务行为仍由独立回归用例验证。", ""
    ]
    ids = set()
    group = None
    for row in data["mappings"]:
        if set(row) != FIELDS or any(not isinstance(value, str) or not value.strip() for value in row.values()):
            raise ValueError(f"Incomplete protocol mapping: {row}")
        if row["id"] in ids:
            raise ValueError(f"Duplicate protocol mapping ID: {row['id']}")
        ids.add(row["id"])
        for field in ("source_evidence", "target_evidence"):
            if not re.fullmatch(r"https://github\.com/[^/]+/[^/]+/blob/[0-9a-f]{40}/[^\s]+", row[field]):
                raise ValueError(f"Evidence must pin a full Git revision: {row['id']}.{field}")
        current = row["id"].split(".")[0]
        if current != group:
            lines.extend([f"## {current}", ""])
            group = current
        lines.extend([
            f"### `{row['id']}`", "",
            f"- 来源字段：`{row['source_field']}`；状态：`{row['status']}`。",
            f"- 来源解释：{row['source_meaning']}",
            f"- 目标解释：{row['target_meaning']}",
            f"- 固定源码：[来源]({row['source_evidence']})、[目标]({row['target_evidence']})。", ""
        ])
    lines.extend(["[返回协议验证边界](protocol-validation.md) · [返回 README](../README.md)", ""])
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail instead of writing an outdated document")
    arguments = parser.parse_args()
    content = render()
    if arguments.check:
        if not OUTPUT.is_file() or OUTPUT.read_text(encoding="utf-8") != content:
            parser.exit(1, "Protocol mapping reference is stale; run python3 scripts/generate-protocol-mappings.py\n")
        print("Protocol mapping reference is up to date.")
    else:
        OUTPUT.write_text(content, encoding="utf-8")
        print(f"Generated {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
